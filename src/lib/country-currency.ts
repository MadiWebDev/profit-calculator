/**
 * The display currency for an ISO country code, or null when the
 * country is unknown / unmapped. Input is normalised (trimmed,
 * upper-cased); non-string input returns null.
 */
export function currencyForCountry(code: unknown): string | null {
  if (typeof code !== "string") return null;
  const upper = code.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper)) return null;
  return COUNTRY_CURRENCY[upper] ?? null;
}
